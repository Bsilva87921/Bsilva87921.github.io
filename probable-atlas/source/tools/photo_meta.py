#!/usr/bin/env python3
"""Write src/photo-meta.js (PHOTO_META) from the site's assets/photos/photos.json: the final photos only, with
their widths, aspect, blur placeholder, colour, alt text and credit. Run after the Photos workflow changes."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(HERE, '..', 'src')
CANDS = [os.path.join(HERE, '..', '..', 'bsilva87921.github.io', 'assets', 'photos', 'photos.json'),
         os.path.join(HERE, '..', '..', '..', 'assets', 'photos', 'photos.json')]
src = next((p for p in CANDS if os.path.exists(p)), None)
if not src: sys.exit('photos.json not found')
d = json.load(open(src, encoding='utf-8'))
keep = {k: {f: v[f] for f in ('w', 'h', 'sizes', 'lqip', 'color', 'alt', 'credit', 'link', 'license')} for k, v in d.items() if not v.get('try')}
js = ('/* Generated by tools/photo_meta.py from assets/photos/photos.json: sizes, blur placeholders and credits. */\n'
      'const PHOTO_META = ' + json.dumps(keep, separators=(',', ':'), ensure_ascii=False) + ';\n')
open(os.path.join(SRC, 'photo-meta.js'), 'w', encoding='utf-8').write(js)
print('photo-meta.js', len(keep), 'photos', len(js), 'bytes')
